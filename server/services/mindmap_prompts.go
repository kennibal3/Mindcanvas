// ============================================================
// REQ-068 二期：思维导图流水线的提示词
//
// 为什么拆成「骨架 → 展开 → 定向重写」而不是一次出整张图：
// 弱模型一次要同时做「选框架、切分维度、写内容、控格式」，每一件都可能出错，
// 而且错了不知道是哪一件。拆开后每步任务小、输出短，且骨架那一步是「选择题」
// ——弱模型选框架比自由发挥稳得多。
//
// 输出一律是「缩进大纲」而不是 JSON：树结构由前端 markdownToDiagram 保证
// （单根、无环、id 唯一），弱模型最容易错的 parent/id 整个消失。
// 大纲里的两种可选标记与前端解析器约定一致（见 web/src/utils/markdownToDiagram.ts）：
//   「标题 :: 说明」  空白包围的 :: 拆出补充说明
//   「★ 标题」        重点
// 约定变更必须前后端一起改，并更新 contracts/mindmap_outline.json 共享样例。
//
// 提示词里的示例刻意选与常见教学材料无关的话题（垃圾分类），
// 防止测试/使用时模型把示例内容抄进输出。
// ============================================================

// MindmapSupplementMark 模型补充（原文没有）的内容必须带的前缀。
// 与提示词里的「（补充）」保持一致；体检与前端提示都认这个字面量。
const MindmapSupplementMark = "（补充）"

// MindmapFrameworks 备选框架。骨架阶段让模型从中「选一个」。
// 名称必须与提示词一致，pipeline 只做记录不做校验——模型选了表外的名字不致命。
var MindmapFrameworks = []string{
	"教学环节", "知识体系", "5W1H", "问题解决", "时间脉络", "对比分类", "项目管理", "自然主题",
}

const mindmapSkeletonPrompt = `你是一名教学内容的信息架构师。请先为用户提供的材料选定一个组织框架，再给出思维导图的骨架——只有中心主题和主分支，不要写子要点。

可选框架（选最贴合材料的一个；都不贴合就选「自然主题」）：
- 教学环节：导入、新授、练习、总结（适合教案、课堂设计）
- 知识体系：概念、原理、方法、应用（适合知识点梳理）
- 5W1H：谁、做什么、何时、何地、为什么、怎么做（适合事件、通知、活动方案）
- 问题解决：现状、问题、原因、对策、预期（适合分析、汇报）
- 时间脉络：按阶段先后（适合计划、进度、历史）
- 对比分类：按对象或类别并列比较（适合比较、选型）
- 项目管理：目标、任务、资源、风险、成效（适合项目方案）
- 自然主题：材料没有明显框架时，按材料自身最自然的主题来分

输出格式（只输出下面这些，不要解释，不要代码围栏）：
框架：<框架名>
# <中心主题>
## <表情符号> <分支名>
## <表情符号> <分支名>

要求：
1. 主分支 4 到 7 个；材料很短、内容确实不多时 3 到 4 个也可以。
2. 所有主分支按同一个维度切分（例如都是「环节」，或都是「对象」），不要把不同维度的东西混在一起。
3. 分支名是名词短语，不超过 12 个字，前面加 1 个贴切的表情符号。
4. 分支要覆盖材料的全部重点，彼此不重复、不遗漏；顺序按材料的逻辑或先后。
5. 中心主题要说清材料真正讲的是什么，不要写成「总览」「概述」这类空话；开头可以带 1 个表情符号。
6. 不要编造材料里没有的内容。

示例：
框架：问题解决
# ♻️ 社区垃圾分类推进方案
## 📊 现状
## ⚠️ 主要问题
## 🔍 原因分析
## 🛠 对策措施
## 🎯 预期成效`

