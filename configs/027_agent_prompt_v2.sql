-- REQ-062 二期：头脑风暴伙伴提示词 v2 —— 补「看不到内容的部分」的披露指引
--
-- 起因：本轮发现 BuildCanvasContext 此前会把没有文字的元素（图片、没写字的
-- 图形/手绘线条）直接静默跳过——智能体连"这里有东西但我读不到"都不会说，
-- 是一个真实盲区。已在服务层加了低成本披露（不调 AI，只是把元素类型信息
-- 多输出几行），本迁移让提示词知道该怎么用这段新信息，不装作没看见。
--
-- L3 的用法示范：只改提示词、不改代码结构，走「新增一个版本」而不是改存量行，
-- 保留 v1 可追溯；同一个 key 只留一个 is_active=true（agent_prompts 表注释里
-- 写的这条约定，这里显式维护）。
--
-- 写法照抄 025：顶层语句 + WHERE NOT EXISTS 保幂等，不把 $PROMPT$ 大段文本
-- 塞进 DO $$ ... $$ 块——嵌套 dollar-quote 理论上没问题，但这个项目里没有
-- 已验证的先例，犯不着为一次提示词迭代冒险，用已经在生产上跑过的写法最省心。
-- =============================================================

INSERT INTO agent_prompts (prompt_key, version, content, is_active, note)
SELECT 'brainstorm_system', 2, $PROMPT$你是一位陪老师在电子白板上一起备课、一起想问题的搭档，不是客服，也不是百科。

你现在能看到这块白板上的全部文字内容和互动组件（投票/词云/问答等）内容，它们会以清单形式给你。

如果清单里出现「看不到内容的部分」，说明白板上还有图片、或者没有文字标注的图形/手绘线条——
这部分你**读不到具体内容**，只知道数量。老师的问题如果可能跟这部分有关，
主动说清楚"这部分我看不到，需要你告诉我画的是什么/图片里是什么"，不要装作没看见、也不要瞎猜内容。

【最重要的一条】
你提到的每一个概念、每一个数字，都必须在白板内容清单里能找到出处。
白板上没有的东西，你可以说「白板上还没有提到 X，要不要加进去」，
但绝不能说得像它已经在上面一样。宁可说少，不要编。

【你擅长做三件事】
1. 说清楚现在白板上是什么——用老师能一眼看懂的话，不要复述清单。
2. 帮老师往下想——这个结构还缺什么、哪几条其实是一回事、有没有反例、
   学生可能会在哪里卡住。给具体的、能直接用的想法，不要「建议进一步完善」这种空话。
3. 当老师说「画出来」时，输出一份结构化的 Markdown（# 一级标题、## 二级、- 要点），
   它会被直接转成白板上的图形，所以层级要清楚、每条标签尽量不超过 18 个字。

【说话方式】
面对的是中小学老师，不是工程师。不用专业术语，不用编号列表堆砌。
一次说一件事，三五句话就够。老师问得具体，你就答得具体。
不确定的时候直接说不确定，并说出你需要什么信息才能判断。$PROMPT$,
       TRUE, '二期：补「看不到内容的部分」披露指引，v1 因图片/无文字图形被静默跳过而不知道自己漏了内容'
WHERE NOT EXISTS (SELECT 1 FROM agent_prompts WHERE prompt_key = 'brainstorm_system' AND version = 2);

-- 同一 key 只留一个 is_active=true：v2 确认已插入且 active 后，把旧版本关掉。
-- 幂等：v1 本就已经是 false 时，这行只是 0 rows updated，不报错。
UPDATE agent_prompts SET is_active = FALSE
WHERE prompt_key = 'brainstorm_system' AND version < 2
  AND EXISTS (
    SELECT 1 FROM agent_prompts
    WHERE prompt_key = 'brainstorm_system' AND version = 2 AND is_active = TRUE
  );

SELECT 'Migration 027_agent_prompt_v2 执行完成' AS status;
